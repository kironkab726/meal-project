-- 1) 레시피 테이블 (메뉴 하나에 레시피 하나) -------------------------------------
create table if not exists public.recipes (
  menu_id     bigint primary key references public.menus (id) on delete cascade,
  minutes     int check (minutes > 0),                              -- 조리 시간(분)
  difficulty  text check (difficulty in ('쉬움', '보통', '어려움')),
  servings    int check (servings > 0),                             -- 몇 인분
  ingredients text not null default '',                             -- 한 줄에 재료 하나
  steps       text not null default '',                             -- 한 줄에 순서 하나
  tip         text,                                                 -- 냥빵이 팁
  updated_at  timestamptz not null default now()
);


-- 2) 권한: 레시피는 누구나 읽기만 --------------------------------------------------
alter table public.recipes enable row level security;

grant select on public.recipes to anon, authenticated;

drop policy if exists "recipes are readable by everyone" on public.recipes;
create policy "recipes are readable by everyone" on public.recipes
  for select to anon, authenticated
  using (true);


